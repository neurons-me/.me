// Builds Meta/demo-data.js from the repo: the eval items, the REAL recorded muse-spark-1.3 outputs (eval/results), and the
// system prompt + few-shot examples (for live mode). Run: node LLMS/Meta/build-data.mjs
import fs from "node:fs"; import path from "node:path"; import { fileURLToPath } from "node:url";
const L = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const rd = (f) => fs.readFileSync(path.join(L, f), "utf8");
const items = Object.fromEntries(rd("eval/eval.jsonl").trim().split("\n").map((l) => JSON.parse(l)).map((x) => [x.id, x]));
const run = JSON.parse(rd("eval/results/meta-muse-spark-1.3-2026-10-29.json"));
const recorded = run.rows.map((r) => ({ id: r.id, lang: r.lang, text: r.text, state: items[r.id].state ?? {}, speaker: items[r.id].speaker, ops: r.predicted, ms: r.ms, attempts: r.attempts }));
let runInfo = { model: run.summary.model, date: run.summary.date, file: "LLMS/eval/results/meta-muse-spark-1.3-2026-10-29.json" };
// English re-recording of the demo chips (LLMS/typescript/record-demo.ts) replaces those rows when present
const enF = path.join(L, "Meta/recorded-en.json");
let thread = null;
if (fs.existsSync(enF)) { const en = JSON.parse(fs.readFileSync(enF, "utf8"));
  // new format: one conversation (thread), replayed in order in a single chat
  if (Array.isArray(en.thread)) thread = en.thread.map((x) => ({ id: x.id, lang: "en", text: x.text, state: x.state, ops: x.ops, reply: x.reply, context: x.context, ok: x.ok, errors: x.errors, ms: x.ms, attempts: x.attempts }));
  (en.rows ?? []).forEach((x) => { const i = recorded.findIndex((r) => r.id === x.id), row = { id: x.id, lang: "en", text: x.text, state: x.state, speaker: x.speaker, ops: x.ops, ms: x.ms, attempts: x.attempts };
    if (i >= 0) recorded[i] = row; else recorded.push(row); });
  runInfo = { model: en.model, date: en.date, file: "LLMS/Meta/recorded-en.json" }; }
const data = { run: runInfo, recorded, ...(thread ? { thread } : {}),
  system: rd("prompt/system.md").trim(), examples: JSON.parse(rd("prompt/examples.json")) };
fs.writeFileSync(path.join(L, "Meta/demo-data.js"), "/*! generated by LLMS/Meta/build-data.mjs from eval/ and prompt/ - do not edit */\nwindow.MetaDemoData = " + JSON.stringify(data) + ";\n");
console.log("recorded", recorded.length);
